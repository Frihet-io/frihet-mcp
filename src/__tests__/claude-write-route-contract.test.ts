/**
 * Two independent contracts, captured on the wire.
 *
 * The Claude pilot credential carries the generic `write` scope. On its own the
 * ERP would honour that scope on every mutating route, including the ones this
 * profile excludes on purpose (delete_client, send_quote, refund_sale, ...): in
 * this repository the exclusion lives only in the Worker's registration
 * interceptor. The ERP-side write-route ceiling for keys stored with
 * `accessProfile: "claude"` (Frihet-ERP `functions/src/publicApi/claudeWriteRoutes.ts`)
 * remains the immutable historical credential ceiling. The consultation Worker
 * does not expose those writes. A Worker deploy still requires an ERP receipt
 * showing that exact historical ceiling
 * deployed (`scripts/check-claude-hosted-release.mjs`, `assertErpCeilingDeployed`).
 *
 * The historical test drives its frozen write-tool names through the GENERAL
 * profile and a REAL FrihetClient, preserving the exact ceiling proof without
 * pretending those handlers remain registered in Claude. The separate served
 * contract drives every consultation handler, requires its exact GET routes,
 * and rejects every excluded handler before any API request.
 * `CLAUDE_WRITE_ROUTES_SHA256` is the same
 * literal the ERP ceiling's test pins. The two copies are kept equal by hand: no
 * CI job compares the two repositories, so a change on one side must be repeated
 * on the other. The deploy check above compares the deployed ERP list with this
 * fixture.
 *
 * Neither fixture is regenerated by this test. A credential-ceiling change is
 * a separate reviewed ERP release, not a side effect of shrinking this surface.
 */

